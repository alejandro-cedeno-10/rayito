"""Render the agent template's package data into the TypeScript SDK
(ai-agent-fast-start, design.md §5).

Single source: ``clients/python/src/rayito/_agent/_assets/`` (the
hash-locked requirements files of deepagents, Strands, the Strands harness,
Hermes and the AgentCore credential helper, the ``rayito-agent-prefetch``
daemon, the Node bridge with its Strands, LangGraph, AI SDK and callable
adapters, ``aws_env_credentials.py``, agentcore-deploy, and ``aws_secret_env.py``,
agent-secret-env) and
``clients/python/src/rayito/_agent/_runner/agent_host/`` (the in-VM agent host,
ADR-028), which the Python SDK ships as package data.
Output, deterministic: ``clients/typescript/src/agent/assets/
template-assets.gen.ts`` with those assets as string constants and
``host-assets.gen.ts`` with every host file keyed by its path under
``agent_host/`` (an empty record while the package has no host), so
``AgentTemplate`` writes the same build context in both SDKs.

Usage::

    python scripts/gen_agent_template_assets.py           # render
    python scripts/gen_agent_template_assets.py --check   # exit 1 on drift
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
ASSETS_DIR = REPO_ROOT / "clients" / "python" / "src" / "rayito" / "_agent" / "_assets"
TARGET = (
    REPO_ROOT
    / "clients"
    / "typescript"
    / "src"
    / "agent"
    / "assets"
    / "template-assets.gen.ts"
)
HOST_DIR = ASSETS_DIR.parent / "_runner" / "agent_host"
HOST_TARGET = (
    REPO_ROOT
    / "clients"
    / "typescript"
    / "src"
    / "agent"
    / "assets"
    / "host-assets.gen.ts"
)
HOST_HEADER = (
    "// GENERATED by scripts/gen_agent_template_assets.py from\n"
    "// clients/python/src/rayito/_agent/_runner/agent_host/. Do not edit by hand: run\n"
    "// `python scripts/gen_agent_template_assets.py`.\n"
)
HOST_SUFFIX = ".py"
CONSTANTS = (
    ("DEEPAGENTS_REQUIREMENTS", "requirements-deepagents.txt"),
    ("PREFETCH_SCRIPT", "rayito-agent-prefetch"),
    ("STRANDS_REQUIREMENTS", "requirements-strands.txt"),
    ("STRANDS_HARNESS_REQUIREMENTS", "requirements-strands-harness.txt"),
    ("HERMES_REQUIREMENTS", "requirements-hermes.txt"),
    ("NODE_BRIDGE", "node_bridge.mjs"),
    ("AWS_CREDENTIALS_REQUIREMENTS", "requirements-aws-credentials.txt"),
    ("AWS_ENV_CREDENTIALS_SCRIPT", "aws_env_credentials.py"),
    ("AWS_SECRET_ENV_SCRIPT", "aws_secret_env.py"),
)
HEADER = (
    "// GENERATED by scripts/gen_agent_template_assets.py from\n"
    "// clients/python/src/rayito/_agent/_assets/. Do not edit by hand: run\n"
    "// `python scripts/gen_agent_template_assets.py`.\n"
)


def ts_string_literal(text: str) -> str:
    """A template literal, escaped like `gen_stack_assets.py` does: biome
    keeps it as is, so the output passes `pnpm lint` untouched."""
    escaped = text.replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${")
    return f"`{escaped}`"


def render() -> str:
    parts = [HEADER]
    for constant, name in CONSTANTS:
        text = (ASSETS_DIR / name).read_text(encoding="utf-8")
        parts.append(f"export const {constant} = {ts_string_literal(text)};\n")
    return "\n".join(parts)


def host_files() -> dict[str, str]:
    """Every ``.py`` file of the agent host, keyed by its path relative to
    ``agent_host/`` (never ``__pycache__``); empty while the host does not
    exist."""
    if not HOST_DIR.is_dir():
        return {}
    return {
        path.relative_to(HOST_DIR).as_posix(): path.read_text(encoding="utf-8")
        for path in sorted(HOST_DIR.rglob(f"*{HOST_SUFFIX}"))
        if "__pycache__" not in path.parts
    }


def render_host() -> str:
    files = host_files()
    if not files:
        return f"{HOST_HEADER}\nexport const AGENT_HOST_FILES: Readonly<Record<string, string>> = {{}};\n"
    entries = "".join(
        f"  {json.dumps(path)}: {ts_string_literal(text)},\n"
        for path, text in files.items()
    )
    return (
        f"{HOST_HEADER}\nexport const AGENT_HOST_FILES: Readonly<Record<string, string>> = {{\n"
        f"{entries}}};\n"
    )


def main(argv: list[str]) -> int:
    outputs = ((TARGET, render()), (HOST_TARGET, render_host()))
    if "--check" in argv:
        stale = [
            target
            for target, expected in outputs
            if (target.read_text(encoding="utf-8") if target.exists() else "") != expected
        ]
        for target in stale:
            print(f"gen_agent_template_assets: {target.relative_to(REPO_ROOT)} is stale; run the script")
        if stale:
            return 1
        print("gen_agent_template_assets: OK")
        return 0
    for target, expected in outputs:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(expected, encoding="utf-8")
        print(f"gen_agent_template_assets: wrote {target.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
