"""Render the SDK detection-rules modules from ``agent-detection.json``.

``agent-detection.json`` at the repository root is the single source of the
rules ``rayito agent deploy`` / ``deploy_agent`` / ``deployAgent`` use to
detect an existing agent project (manifests, frameworks, entrypoint
patterns, routes, install plans, version sources, providers). This script
renders it into ``clients/python/src/rayito/_agent/_detection_rules.py`` and
``clients/typescript/src/agent/detection-rules.gen.ts`` so neither SDK can
drift from the other, and refuses a rule file whose regular expressions leave
the subset Python and JavaScript share. Standard library only.

Usage::

    python scripts/gen_agent_detection.py           # rewrite both modules
    python scripts/gen_agent_detection.py --check   # exit 1 with a diff on drift
"""

from __future__ import annotations

import difflib
import json
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
RULES_JSON = REPO_ROOT / "agent-detection.json"
LIMITS_JSON = REPO_ROOT / "limits.json"
PYTHON_TARGET = (
    REPO_ROOT / "clients" / "python" / "src" / "rayito" / "_agent" / "_detection_rules.py"
)
TYPESCRIPT_TARGET = REPO_ROOT / "clients" / "typescript" / "src" / "agent" / "detection-rules.gen.ts"
JSON_INDENT = 1
RULES_SCHEMA_KEY = "agentDetectionRulesSchema"
PATTERN_KEYS = frozenset({"pattern", "requires"})
TEMPLATE_KEYS = frozenset(
    {
        "requestFieldTemplates",
        "responseFieldTemplates",
        "portEnvTemplates",
        "portLiterals",
        "models",
    }
)
#: Constructs that Python's `re` and JavaScript's `RegExp` do not read the
#: same way: lookaround, named groups, inline flags and `\A` / `\Z` anchors.
FORBIDDEN_CONSTRUCTS = (
    re.compile(r"\(\?<"),
    re.compile(r"\(\?="),
    re.compile(r"\(\?!"),
    re.compile(r"\(\?P"),
    re.compile(r"\(\?[aiLmsux]"),
    re.compile(r"\\[AZ]"),
)
PLACEHOLDER = re.compile(r"\{(?:field|env)\}")
PYTHON_HEADER = '''"""Reglas de detección de proyectos de agente (`agent-detection.json`).

GENERADO por `scripts/gen_agent_detection.py` desde `agent-detection.json`
(raíz del repo): no editar a mano, ejecutar `make agent-detection`. Los
esquemas y las reglas son los mismos que usa el SDK de TypeScript
(`agent/detection-rules.gen.ts`).
"""

from __future__ import annotations

import json
from collections.abc import Mapping
from typing import Any, Final

_RULES_JSON: Final = r"""'''
PYTHON_FOOTER = '''"""

DETECTION_RULES: Final[Mapping[str, Any]] = json.loads(_RULES_JSON)
'''
TYPESCRIPT_HEADER = (
    "// GENERATED by scripts/gen_agent_detection.py from agent-detection.json "
    "(repository root).\n"
    "// Do not edit by hand: run `make agent-detection`. The Python SDK renders the same "
    "rules.\n\n"
)


def load_rules() -> dict[str, object]:
    with RULES_JSON.open(encoding="utf-8") as handle:
        rules = json.load(handle)
    with LIMITS_JSON.open(encoding="utf-8") as handle:
        schema = json.load(handle)[RULES_SCHEMA_KEY]
    if rules.get("schema") != schema:
        raise SystemExit(f"agent-detection.json: schema debe ser {schema!r}")
    return rules


def patterns(node: object, under_template: bool = False) -> list[str]:
    """Every regular expression in the rules, templates with their
    placeholders filled by a plain word."""
    found: list[str] = []
    if isinstance(node, dict):
        for key, value in node.items():
            template = under_template or key in TEMPLATE_KEYS
            if key in PATTERN_KEYS and isinstance(value, str):
                found.append(value)
            else:
                found.extend(patterns(value, template))
    elif isinstance(node, list):
        for item in node:
            if under_template and isinstance(item, str):
                found.append(PLACEHOLDER.sub("word", item))
            else:
                found.extend(patterns(item, under_template))
    return found


def validate(rules: dict[str, object]) -> None:
    for pattern in patterns(rules):
        for construct in FORBIDDEN_CONSTRUCTS:
            if construct.search(pattern):
                raise SystemExit(
                    f"agent-detection.json: la expresión {pattern!r} usa una construcción "
                    "que Python y JavaScript no leen igual"
                )
        try:
            re.compile(pattern, re.MULTILINE | re.ASCII)
        except re.error as exc:
            raise SystemExit(f"agent-detection.json: expresión inválida {pattern!r}: {exc}")


def canonical(rules: dict[str, object]) -> str:
    return json.dumps(rules, indent=JSON_INDENT, ensure_ascii=False)


def render_python(rules: dict[str, object]) -> str:
    text = canonical(rules)
    if '"""' in text:
        raise SystemExit("agent-detection.json: no puede contener tres comillas dobles seguidas")
    return f"{PYTHON_HEADER}\n{text}\n{PYTHON_FOOTER}"


def render_typescript(rules: dict[str, object]) -> str:
    literal = json.dumps(canonical(rules), ensure_ascii=False)
    return f"{TYPESCRIPT_HEADER}export const DETECTION_RULES_JSON = {literal};\n"


def current_text(path: Path) -> str:
    return path.read_text(encoding="utf-8") if path.exists() else ""


def write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


def check(renders: dict[Path, str]) -> int:
    drifted = 0
    for path, expected in renders.items():
        actual = current_text(path)
        if actual == expected:
            continue
        drifted += 1
        relative = path.relative_to(REPO_ROOT).as_posix()
        diff = difflib.unified_diff(
            actual.splitlines(keepends=True),
            expected.splitlines(keepends=True),
            fromfile=f"{relative} (on disk)",
            tofile=f"{relative} (from agent-detection.json)",
            n=1,
        )
        sys.stdout.write(f"gen_agent_detection: {relative} drifts from agent-detection.json\n")
        sys.stdout.writelines(diff)
    if drifted:
        sys.stdout.write(
            "gen_agent_detection: run `python scripts/gen_agent_detection.py` to regenerate\n"
        )
    return 1 if drifted else 0


def main(argv: list[str]) -> int:
    rules = load_rules()
    validate(rules)
    renders = {
        PYTHON_TARGET: render_python(rules),
        TYPESCRIPT_TARGET: render_typescript(rules),
    }
    if "--check" in argv:
        return check(renders)
    for path, text in renders.items():
        write_text(path, text)
        sys.stdout.write(f"gen_agent_detection: wrote {path.relative_to(REPO_ROOT).as_posix()}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
